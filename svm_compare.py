# 转成 DataFrame 方便处理
memo_df = pd.DataFrame(raw_data, columns=['text', 'label'])

# 切分数据集
x_train, x_test, y_train, y_test = train_test_split(memo_df['text'], memo_df['label'], test_size=0.2, random_state=42)

# 提取特征，这里直接用字符切分，省去了装 jieba 的麻烦
vectorizer = TfidfVectorizer(analyzer='char', ngram_range=(1, 2))
train_vec = vectorizer.fit_transform(x_train)
test_vec = vectorizer.transform(x_test)

# --- 跑朴素贝叶斯 ---
nb = MultinomialNB()
nb.fit(train_vec, y_train)
nb_res = nb.predict(test_vec)
print("【朴素贝叶斯测试报告】")
print(classification_report(y_test, nb_res))

# --- 跑个 SVM 做对照 ---
svm = SVC(kernel='linear')
svm.fit(train_vec, y_train)
svm_res = svm.predict(test_vec)
print("\n【SVM 测试报告】")
print(classification_report(y_test, svm_res))